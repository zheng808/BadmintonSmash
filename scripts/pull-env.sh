#!/usr/bin/env bash
# Writes client/.env.<env> from the deployed CloudFormation stack outputs.
# Usage: scripts/pull-env.sh <dev|prod>
set -euo pipefail

ENV_NAME="${1:?usage: scripts/pull-env.sh <dev|prod>}"
REGION="${AWS_REGION:-${CDK_REGION:-us-west-2}}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_FILE="$ROOT/client/.env.$ENV_NAME"

output() {
  aws cloudformation describe-stacks \
    --region "$REGION" \
    --stack-name "Smash-$ENV_NAME-$1" \
    --query "Stacks[0].Outputs[?OutputKey=='$2'].OutputValue" \
    --output text
}

API_URL="$(output Backend ApiUrl)"
USER_POOL_ID="$(output Backend UserPoolId)"
USER_POOL_CLIENT_ID="$(output Backend UserPoolClientId)"
OAUTH_DOMAIN="$(output Backend CognitoDomain)"
WEB_URL="$(output Web WebUrl)"
WEB_BUCKET="$(output Web WebBucketName)"
DISTRIBUTION_ID="$(output Web DistributionId)"

cat > "$OUT_FILE" <<ENV
# Generated by scripts/pull-env.sh from stack outputs. Do not edit by hand.
EXPO_PUBLIC_APP_ENV=$ENV_NAME
EXPO_PUBLIC_API_URL=$API_URL
EXPO_PUBLIC_USER_POOL_ID=$USER_POOL_ID
EXPO_PUBLIC_USER_POOL_CLIENT_ID=$USER_POOL_CLIENT_ID
EXPO_PUBLIC_OAUTH_DOMAIN=$OAUTH_DOMAIN
EXPO_PUBLIC_WEB_URL=$WEB_URL
EXPO_PUBLIC_REGION=$REGION
ENV

echo "Wrote $OUT_FILE"
echo "WebBucketName=$WEB_BUCKET"
echo "DistributionId=$DISTRIBUTION_ID"

# --- web/ (Vite SPA) -----------------------------------------------------------
# Same stack outputs, written as VITE_* for web/.env.<env>. GOOGLE_MAPS_KEY is optional.
GOOGLE_SIGNIN="$(output Persistence GoogleSignIn 2>/dev/null || echo disabled)"
WEB_OAUTH_DOMAIN="$OAUTH_DOMAIN"; [ "$GOOGLE_SIGNIN" = "enabled" ] || WEB_OAUTH_DOMAIN=""
WEB_OUT_FILE="$ROOT/web/.env.$ENV_NAME"
cat > "$WEB_OUT_FILE" <<ENV
# Generated by scripts/pull-env.sh from stack outputs. Do not edit by hand.
VITE_API_URL=$API_URL
VITE_USER_POOL_ID=$USER_POOL_ID
VITE_USER_POOL_CLIENT_ID=$USER_POOL_CLIENT_ID
VITE_OAUTH_DOMAIN=$WEB_OAUTH_DOMAIN
VITE_WEB_URL=$WEB_URL
VITE_GOOGLE_MAPS_KEY=${GOOGLE_MAPS_KEY:-}
VITE_DEV_AUTH=0
ENV
echo "Wrote $WEB_OUT_FILE"
